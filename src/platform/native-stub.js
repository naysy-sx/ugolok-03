// Общий помощник для capacitor.js/tauri.js — методы, которые в конкретном
// Э ещё не реализованы, бросают явно (тот же принцип, что весь адаптер в
// Э1.2: тихий no-op на фактически отсутствующей возможности прячет дыру до
// первого живого теста на устройстве, явный throw — нет). НЕ содержит и не
// импортирует @capacitor/*/@tauri-apps/* — это чистая обвязка, безопасно
// использовать из обоих файлов (§4.2 ограничивает только native SDK импорты,
// не обычные локальные модули).
export function notImplemented(shell, path) {
	return () => {
		throw new Error(`platform.${path} (${shell}) — ещё не реализовано`);
	};
}
