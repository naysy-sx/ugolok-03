// Этап 74 — найдено живой проверкой (тот же класс, что М3 этапа 73.4, но для
// контента каналов, не личных сообщений): relay не гарантирует порядок доставки
// между "грант на новую версию ключа" (kind 30053, отдельная подписка) и
// "контент, зашифрованный этой версией" (kind 30060/30054/30061/30062/30063,
// #h-топик подписка) — событие контента может прийти РАНЬШЕ, чем локально
// применится нужная версия ключа. Сигнал ОТДЕЛЬНЫЙ от обычного "не мой канал"/
// "устаревшая версия" (те остаются тихим no-op, не retriable) — брошен ТОЛЬКО
// когда решение "применять ли" зависит от версии ключа, которой ЕЩЁ нет
// локально, и есть шанс, что она появится (тот же приём, что MLS "invalid MAC"
// в receiveGroupMessageEvent — там тоже НЕ пытаются отличить "рано" от
// "навсегда сломано", TTL сам избавится от неисправимых).
export class ChannelContentNotReadyError extends Error {
	constructor(message = "channel content: локальная версия ключа канала ещё не готова") {
		super(message);
		this.name = "ChannelContentNotReadyError";
	}
}
